import { CellValue } from "jspreadsheet-ce";
import { splitDataByBlankRows } from "../src/js/splitTableData.js";

// getData() の processed 指定時は行が {"0": 値, "1": 値} 形式のオブジェクトで返る
test('オブジェクト形式の行でも空白行を判定して分割できる', () => {
  const rows = [
    { 0: 100, 1: 200 },
    { 0: '', 1: '' },
    { 0: 400, 1: 400 },
  ] as unknown as CellValue[][];
  expect(splitDataByBlankRows(rows)).toEqual([
    [{ 0: 100, 1: 200 }],
    [{ 0: 400, 1: 400 }],
  ]);
});

test('空白行がなければ全体が1グループになる', () => {
  expect(splitDataByBlankRows([
    ['100', '200'],
    ['200', '100'],
  ])).toEqual([
    [['100', '200'], ['200', '100']],
  ]);
});

test('空白行を区切りとして複数グループに分割される', () => {
  expect(splitDataByBlankRows([
    ['100', '200'],
    ['200', '100'],
    ['200', '200'],
    ['', ''],
    ['400', '400'],
    ['400', '500'],
    ['500', '400'],
    ['500', '500'],
    ['', ''],
    ['700', '700'],
    ['700', '800'],
    ['800', '700'],
    ['800', '800'],
  ])).toEqual([
    [['100', '200'], ['200', '100'], ['200', '200']],
    [['400', '400'], ['400', '500'], ['500', '400'], ['500', '500']],
    [['700', '700'], ['700', '800'], ['800', '700'], ['800', '800']],
  ]);
});

test('連続した空白行や先頭・末尾の空白行で空グループは作られない', () => {
  expect(splitDataByBlankRows([
    ['', ''],
    ['100', '200'],
    ['', ''],
    ['', ''],
    ['400', '400'],
    ['', ''],
  ])).toEqual([
    [['100', '200']],
    [['400', '400']],
  ]);
});

test('空白のみのセルやnull・undefinedも空白行として扱う', () => {
  expect(splitDataByBlankRows([
    ['100', '200'],
    [' ', '　'],
    ['400', '400'],
    [null as unknown as string, undefined as unknown as string],
    ['700', '700'],
  ])).toEqual([
    [['100', '200']],
    [['400', '400']],
    [['700', '700']],
  ]);
});

test('片方のセルにだけ値がある行は空白行として扱わない', () => {
  expect(splitDataByBlankRows([
    ['100', '200'],
    ['300', ''],
    ['400', '400'],
  ])).toEqual([
    [['100', '200'], ['300', ''], ['400', '400']],
  ]);
});

test('全行が空白なら空配列を返す', () => {
  expect(splitDataByBlankRows([['', ''], ['', '']])).toEqual([]);
  expect(splitDataByBlankRows([])).toEqual([]);
});
